/* ------------------------------------------------------------------ colour maths */

const srgbToLinear = (c) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
const linearToSrgb = (c) => (c <= 0.0031308 ? c * 12.92 : 1.055 * Math.pow(c, 1 / 2.4) - 0.055);

/* OKLCH -> linear sRGB -> sRGB. Björn Ottosson's matrices. */
function oklchToRgb(L, C, h) {
  const hr = (h * Math.PI) / 180;
  const a = C * Math.cos(hr);
  const b = C * Math.sin(hr);

  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ * l_ * l_, m = m_ * m_ * m_, s = s_ * s_ * s_;

  return [
    linearToSrgb(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
    linearToSrgb(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
    linearToSrgb(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s),
  ];
}

const IN_GAMUT = (rgb) => rgb.every((c) => c >= -0.0002 && c <= 1.0002);

/* Reduce chroma until the colour is representable in sRGB. Reducing chroma rather than
   clipping channels keeps the hue and the lightness — clipping shifts both, which is how
   two steps of the same scale end up looking like different hues. */
function gamutFit(L, C, h) {
  if (IN_GAMUT(oklchToRgb(L, C, h))) return C;
  let lo = 0, hi = C;
  for (let i = 0; i < 24; i++) {
    const mid = (lo + hi) / 2;
    if (IN_GAMUT(oklchToRgb(L, mid, h))) lo = mid; else hi = mid;
  }
  return lo;
}

function toHex(L, C, h) {
  const C2 = gamutFit(L, C, h);
  const rgb = oklchToRgb(L, C2, h).map((c) => Math.max(0, Math.min(255, Math.round(c * 255))));
  return '#' + rgb.map((v) => v.toString(16).padStart(2, '0')).join('');
}

const hexToRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const relLum = (hex) => {
  const [r, g, b] = hexToRgb(hex).map((v) => srgbToLinear(v / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const x = relLum(a), y = relLum(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
};

/* ---------------------------------------------------- colour-vision simulation */

/* Viénot, Brettel & Mollon (1999) dichromat simulation. The matrices operate on LINEAR
 * sRGB, which is why the conversion happens either side of them.
 *
 * This exists because six independent critiques of three different palettes all reached the
 * same conclusion: the seven syntax colours were separated by HUE ALONE and all sat on one
 * lightness step, so a red-green dichromat saw three or four colours rather than seven. Hue
 * separation cannot be fixed by rotating hues — the wheel folds onto a line — so lightness
 * has to carry a share of the difference. An obligation that is not measured is a wish, so
 * the simulation is here rather than in a comment. */
const CVD = {
  deuteranopia: [[0.625, 0.375, 0.0], [0.700, 0.300, 0.0], [0.0, 0.300, 0.700]],
  protanopia: [[0.1667, 0.8333, 0.0], [0.1667, 0.8333, 0.0], [0.0, 0.1250, 0.8750]],
};

function simulate(hex, kind) {
  const m = CVD[kind];
  const lin = hexToRgb(hex).map((v) => srgbToLinear(v / 255));
  const out = m.map((row) => row[0] * lin[0] + row[1] * lin[1] + row[2] * lin[2]);
  const rgb = out.map((c) => Math.max(0, Math.min(255, Math.round(linearToSrgb(Math.max(0, Math.min(1, c))) * 255))));
  return '#' + rgb.map((v) => v.toString(16).padStart(2, '0')).join('');
}

/* ------------------------------------------------------------------ scale building */

/* Seed lightness per step. These are starting points only; anything with a contrast
   obligation is moved until it meets it, so a seed being slightly off costs nothing. */
const L_LIGHT = [0.993, 0.976, 0.952, 0.930, 0.906, 0.874, 0.826, 0.740, 0.586, 0.548, 0.512, 0.242];
const L_DARK  = [0.178, 0.212, 0.256, 0.292, 0.324, 0.372, 0.436, 0.524, 0.640, 0.686, 0.782, 0.948];

/* Chroma multiplier per step: quiet at the background end, peaking at the solid fill,
   easing off again for text so a caption reads as text rather than as a coloured object. */
const C_CURVE = [0.055, 0.095, 0.175, 0.255, 0.330, 0.415, 0.510, 0.660, 1.000, 0.975, 0.720, 0.360];

/* The obligations. Indices are 1-based step numbers to match the vocabulary above.
 *
 * step12 is 10.0 and not 13.0 for a measured reason: in dark mode the most contrasting
 * surface text is allowed to sit on is gray.4, and pure white against it tops out at
 * 14.17:1 — so a 13:1 obligation is satisfiable only by abandoning the scale's tint
 * entirely and using near-#ffffff. 10:1 is comfortably past AAA (7:1), holds on every
 * surface rather than only on the page, and leaves the neutral its hue. */
const NEED = {
  step8: 3.0,    // strong border and graphic line: carries meaning (SC 1.4.11)
  step9: 3.0,    // a solid fill must be distinguishable from the page it sits on
  step11: 4.5,   // low-contrast accessible text (SC 1.4.3)
  step12: 10.0,  // high-contrast text, on every surface
  onSolid: 4.5,  // text placed on step 9

  /* OKLab distance required between two colours that carry different meaning, measured
     AFTER dichromat simulation. Syntax tokens get the lower bar because seven of them have
     to fit on one surface and the alternative is fewer token types; brand hues get the
     higher bar because there are only three and they are the page's structure. */
  cvdSyntax: 0.055,
  cvdBrand: 0.075,
};

/* THE SURFACE SET. Steps 1-4 are the app background, the subtle background and the two
 * component backgrounds — every surface a caption can land on. Text obligations are
 * checked against ALL of them, which is the entire correction: the token this replaces
 * passed on one surface, was never checked against the other two, and failed on both. */
const TEXT_ON = [1, 2, 3, 4];

function buildScale({ hue, chroma, mode, beds, extraBeds, bias }) {
  const Ls = (mode === 'dark' ? L_DARK : L_LIGHT).slice();
  /* A per-hue lightness bias applied to the SOLID and TEXT steps only, so that three brand
     hues differ in lightness as well as in angle. Same reasoning as the syntax tiers: under
     red-green simulation two of the three hues routinely fold together, and lightness is the
     channel that survives. Backgrounds and borders keep their seeds, because shifting those
     would change the surface set every text obligation is measured against. */
  if (bias) [8, 9, 10, 11].forEach((i) => { Ls[i] = Math.max(0.05, Math.min(0.96, Ls[i] + bias)); });
  const dir = mode === 'dark' ? +1 : -1;   // which way is "more contrast against the page"
  const hexAt = (i) => toHex(Ls[i], C_CURVE[i] * chroma, hue);

  /* Steps 1-4 carry no obligation, so they never move and can be resolved up front.
     For a neutral scale they ARE the surface set; for a hue scale the neutral surfaces
     are passed in and this scale's own tints are added — a teal chip label sits on a teal
     tint, and checking only the page background is how that one reached just 3.31:1. */
  const ownSurfaces = TEXT_ON.map((s) => hexAt(s - 1));
  const surfaceBeds = (beds && beds.length ? beds.concat(hexAt(1), hexAt(2)) : ownSurfaces)
    .concat(extraBeds || []);
  const pageBeds = (beds && beds.length ? beds : ownSurfaces).slice(0, 2);

  const walk = (step, target, list) => {
    const i = step - 1;
    for (let n = 0; n < 500; n++) {
      const worst = Math.min(...list.map((bed) => contrast(hexAt(i), bed)));
      if (worst >= target) return true;
      Ls[i] += dir * 0.002;
      if (Ls[i] <= 0.015 || Ls[i] >= 0.997) return false;   // clamped: --verify reports it
    }
    return false;
  };

  walk(8, NEED.step8, surfaceBeds);
  walk(11, NEED.step11, surfaceBeds);
  walk(12, NEED.step12, surfaceBeds);
  walk(9, NEED.step9, pageBeds);

  /* Text on the solid fill. The candidates are the two ends of this scale; if neither
     clears 4.5:1 the SOLID moves, not the obligation. Walking step 9 further from the page
     raises its contrast with whichever end is winning, in both themes — so this converges
     rather than fighting the step-9 walk above. */
  const bestOnSolid = () => Math.max(contrast(hexAt(0), hexAt(8)), contrast(hexAt(11), hexAt(8)));
  for (let n = 0; n < 500 && bestOnSolid() < NEED.onSolid; n++) {
    Ls[8] += dir * 0.002;
    if (Ls[8] <= 0.015 || Ls[8] >= 0.997) break;
  }

  // Step 10 is the hover of step 9: one nudge further from the page, never less.
  Ls[9] = Ls[8] + dir * 0.038;

  const steps = Ls.map((_, i) => hexAt(i));
  const onSolid = contrast(steps[0], steps[8]) >= contrast(steps[11], steps[8]) ? steps[0] : steps[11];

  return { steps, onSolid, surfaces: ownSurfaces, L: Ls.slice() };
}

/* A single colour pinned to a surface — used for the code-block island and for status
   colours, which are not full scales because nothing needs their hover state. */
function pinned({ hue, chroma, bg, target, mode, seedL }) {
  const beds = Array.isArray(bg) ? bg : [bg];
  let L = seedL !== undefined ? seedL : (mode === 'dark' ? 0.70 : 0.55);
  // Walk away from the LIGHTEST bed in a light theme, the darkest in a dark one, so the
  // result clears every bed rather than only the one that happened to be passed first.
  const dir = relLum(beds.reduce((a, b) => (relLum(a) > relLum(b) ? a : b))) > 0.5 ? -1 : +1;
  for (let n = 0; n < 500; n++) {
    const hex = toHex(L, chroma, hue);
    if (Math.min(...beds.map((b) => contrast(hex, b))) >= target) return hex;
    L += dir * 0.002;
    if (L <= 0.015 || L >= 0.997) break;
  }
  return toHex(L, chroma, hue);
}

