/* Palette generator for the CorpusTrace site.
 *
 *   node scripts/generate-palette.mjs            # list configurations
 *   node scripts/generate-palette.mjs <id>       # write that configuration into styles.css
 *   node scripts/generate-palette.mjs <id> --verify   # print every enforced ratio, write nothing
 *   node scripts/generate-palette.mjs <id> --stdout   # print the CSS, write nothing
 *
 * WHY THIS EXISTS
 * ---------------
 * The site's contrast failures were never a hue problem. One token, --text-faint, was
 * placed on three different surfaces and failed at three different ratios (3.03, 3.22,
 * 3.33) — because nothing decided what job that token had. Swapping in a prettier palette
 * and assigning captions to an equally light step reproduces every failure in new hues.
 *
 * So colour is no longer chosen; it is DERIVED. Each scale is twelve steps with a fixed
 * job, borrowed from Radix Colors' step semantics:
 *
 *    1-2   app and subtle backgrounds
 *    3-5   component backgrounds: normal, hover, active
 *    6-8   borders and separators: subtle, normal, strong
 *    9-10  solid fills: normal, hover
 *    11    low-contrast accessible text
 *    12    high-contrast text
 *
 * The VALUES are generated here rather than taken from Radix, for one concrete reason:
 * Radix's scales are tuned for APCA, which models perception better than WCAG 2.x but
 * disagrees with it at the edges — particularly light text on mid-tone backgrounds. Our
 * gate is stated as WCAG AA, so the WCAG number is the one that has to hold, and the only
 * way to hold it is to compute it. Every step below is walked along its lightness axis
 * until it measurably passes, against EVERY surface it is allowed to sit on. That last
 * clause is the whole fix: the old grey passed on one surface and was never checked
 * against the other two.
 *
 * A configuration therefore contains no hex. It contains hue angles and chroma targets —
 * the part that is a design decision — and nothing that could be wrong about arithmetic.
 */

