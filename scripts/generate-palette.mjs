/* ------------------------------------------------- solving the brand-hue biases */

/* Same lesson as the syntax tokens, one level up: hand-picking a lightness bias to separate
 * two brand hues under simulation does not work, because you cannot see post-simulation
 * space from authored space. A bias of 0.075 chosen by eye moved Sextant's amber/jade pair
 * from 0.071 to 0.059 — the wrong way.
 *
 * So the bias is searched rather than chosen. For each configuration the grid below is
 * evaluated over BOTH themes and BOTH dichromat conditions, and the combination with the
 * best worst-case separation wins. This is safe to search freely because buildScale applies
 * the bias BEFORE its contrast walks — every candidate is contrast-valid by construction, so
 * the search can only trade aesthetics, never accessibility.
 *
 * hue1 is held at zero: it is the interface hue and its solid is the one colour a returning
 * visitor recognises, so the other two move around it. */
const BIAS_GRID = [0, 0.02, 0.04, 0.06, 0.08, 0.10, 0.12, 0.15, 0.18];
/* hue1 is the interface hue — the solid a returning visitor recognises — so it is allowed to
   move, but only a little, and the tie-break below prefers leaving it alone. */
const BIAS_GRID_1 = [0, 0.03, 0.06];
const _biasCache = new Map();

function solveBiases(cfg) {
  if (_biasCache.has(cfg.id)) return _biasCache.get(cfg.id);

  const perMode = ['light', 'dark'].map((mode) => {
    const Lseed = mode === 'dark' ? L_DARK : L_LIGHT;
    const washBeds = cfg.hues.flatMap((h) => [2, 3].map((st) =>
      toHex(Lseed[st - 1], C_CURVE[st - 1] * h.chromaPeak, h.hue)));
    const gray = buildScale({ hue: cfg.grayHue, chroma: cfg.grayChroma, mode, extraBeds: washBeds });
    return { mode, beds: gray.surfaces, washBeds };
  });

  const scoreFor = (b2, b3, b1) => {
    let worst = Infinity;
    for (const { mode, beds, washBeds } of perMode) {
      const sgn = mode === 'dark' ? 1 : -1;
      const scales = cfg.hues.map((h, i) => buildScale({
        hue: h.hue, chroma: h.chromaPeak, mode, beds, extraBeds: washBeds,
        bias: sgn * (i === 1 ? b2 : i === 2 ? b3 : b1),
      }));
      for (const kind of ['deuteranopia', 'protanopia']) {
        for (const st of [9, 11]) {
          for (let i = 0; i < scales.length; i++) {
            for (let j = i + 1; j < scales.length; j++) {
              const d = deltaE(simulate(scales[i].steps[st - 1], kind), simulate(scales[j].steps[st - 1], kind));
              if (d < worst) worst = d;
            }
          }
        }
      }
    }
    return worst;
  };

  let best = { score: -1, b1: 0, b2: 0, b3: 0 };
  for (const b1 of BIAS_GRID_1) {
    for (const b2 of BIAS_GRID) {
      for (const b3 of BIAS_GRID) {
        const score = scoreFor(b2, b3, b1);
        // Ties go to the smaller total bias: a scheme should differ by hue where it can, and
        // spend lightness only where hue has stopped working. hue1 is weighted double so it
        // is the last thing the search reaches for.
        const cost = b1 * 2 + b2 + b3;
        const bestCost = best.b1 * 2 + best.b2 + best.b3;
        if (score > best.score + 1e-9
          || (Math.abs(score - best.score) < 1e-9 && cost < bestCost)) {
          best = { score, b1, b2, b3 };
        }
      }
    }
  }
  const out = { hue1: best.b1, hue2: best.b2, hue3: best.b3, score: best.score };
  _biasCache.set(cfg.id, out);
  return out;
}

/* ------------------------------------------------------------------ theme assembly */

function buildTheme(cfg, mode) {
  /* SECTION WASHES, resolved before anything else. Steps 2 and 3 of each brand hue are
     used as a soft wash behind whole sections, so the page changes temperature as the
     reader descends — rule 3 of the hue brief: temperature on surfaces, never on type.
     They can be computed up front because steps 1-4 carry no contrast obligation and are
     therefore just their seeds. Computing them FIRST is the point: every text step below
     is then walked against the washes as well as against the neutral surfaces, so a tinted
     section cannot quietly invalidate a ratio that was verified on the untinted one. */
  const Lseed = mode === 'dark' ? L_DARK : L_LIGHT;
  const washes = cfg.hues.map((h) => ({
    slot: h.slot,
    hexes: [2, 3].map((st) => toHex(Lseed[st - 1], C_CURVE[st - 1] * h.chromaPeak, h.hue)),
  }));
  const washBeds = washes.flatMap((w) => w.hexes);

  const gray = buildScale({ hue: cfg.grayHue, chroma: cfg.grayChroma, mode, extraBeds: washBeds });

  /* The four surfaces text is allowed to land on, resolved from the neutral scale. The
     mapping differs by theme for exactly two roles and that is not an inconsistency:
     in light mode a raised card is WHITER than the page, in dark mode it is LIGHTER than
     the page. Both mean "toward the viewer"; only one of them means "toward step 1". */
  const surfaces = mode === 'dark'
    ? { bg: 1, bgSubtle: 2, surface: 3, raised: 4 }
    : { bg: 2, bgSubtle: 3, surface: 1, raised: 1 };

  /* Every surface text can land on, not merely the ones the four semantic names happen to
     point at — steps 4 and 5 are component hover/active states and text sits on those too. */
  const surfaceHexes = gray.surfaces;

  /* A DELIBERATE DEVIATION from Radix's twelve steps, documented rather than hidden.
     Radix gives exactly two accessible text steps: 11 (low contrast) and 12 (high). This
     page's information design needs three — heading, body, caption — and the old design
     got its third by going lighter than 11, which is precisely why it failed at 3.03:1.
     So the third level is generated INWARD instead: held at AAA 7:1, between 11 and 12.
     Going inward can only ever be safe; going outward is the bug this replaces. */
  const textMid = pinned({ hue: cfg.grayHue, chroma: cfg.grayChroma * 0.62, bg: gray.surfaces.concat(washBeds), target: 7.0, mode });

  const hues = cfg.hues.map((h) => ({
    slot: h.slot,
    scale: buildScale({ hue: h.hue, chroma: h.chromaPeak, mode, beds: surfaceHexes, extraBeds: washBeds,
      bias: (mode === 'dark' ? 1 : -1) * (solveBiases(cfg)[h.slot] || 0) }),
    hue: h.hue,
  }));

  /* The code block is a dark island in BOTH themes, so its tokens are pinned to its own
     surface rather than to the page. In light mode that surface is the one place where a
     light-theme accent has to survive on a dark bed — which is how the focus ring came to
     fail there at 2.82:1 while passing everywhere else. */
  const codeBg = toHex(mode === 'dark' ? 0.168 : 0.202, cfg.code.chroma, cfg.code.hue);
  const codeBorder = toHex(mode === 'dark' ? 0.246 : 0.276, cfg.code.chroma, cfg.code.hue);
  const codeText = pinned({ hue: cfg.code.hue, chroma: 0.010, bg: codeBg, target: 13, mode: 'dark' });
  const codeMuted = pinned({ hue: cfg.code.hue, chroma: 0.014, bg: codeBg, target: 4.5, mode: 'dark' });
  const SYNTAX_CHROMA = 0.115;
  const COMMENT_CHROMA = 0.026;

  /* Every token gets its OWN lightness, deliberately spread. This is the fix for the
     collapse described above: two tokens that a dichromat cannot tell apart by hue are
     still told apart by being visibly lighter or darker. The seeds are spread as widely as
     4.5:1 on the code surface allows; anything that falls short is walked up by pinned(),
     so the spread never costs contrast. */
  const SYNTAX_L = {
    key: 0.615, comment: 0.655, number: 0.690, keyword: 0.730,
    string: 0.765, flag: 0.840, builtin: 0.915,
  };
  // Carry their own non-colour channel (italic / bold), so colour is not their only cue.
  const STYLED = new Set(['comment', 'keyword']);
  const codeTokens = cfg.code.tokens.map((t) => {
    const chroma = t.token === 'comment' ? COMMENT_CHROMA : SYNTAX_CHROMA;
    return {
      token: t.token, hue: t.hue, chroma,
      styled: STYLED.has(t.token),
      L: SYNTAX_L[t.token],
      hex: pinned({ hue: t.hue, chroma, bg: codeBg, target: 4.5, mode: 'dark', seedL: SYNTAX_L[t.token] }),
    };
  });

  /* SEPARATE THE TOKENS IN SIMULATED SPACE, not in authored space.
   *
   * Spreading their authored lightness was not enough, and the reason is worth writing down:
   * dichromat simulation CHANGES lightness. Green carries most of the luminance signal, so a
   * green loses lightness when the red-green axis is collapsed, while a purple gains it —
   * which means two tokens deliberately set 0.15 apart can cross over and land on top of one
   * another. Measured: string at L 0.765 and key at L 0.615 came out 0.023 apart after
   * simulation, against a 0.055 floor.
   *
   * So the obligation is solved where it is stated. Each round finds the closest simulated
   * pair across both conditions and pushes them apart along lightness, refusing any move
   * that would drop a token below 4.5:1 on the code surface — a token that separates by
   * going illegible has not been fixed. */
  {
    const styleless = codeTokens.filter((c) => !c.styled);
    const hexOf = (c) => toHex(c.L, c.chroma, c.hue);
    const simLum = (c, kind) => relLum(simulate(hexOf(c), kind));
    const legible = (c, L) => contrast(toHex(L, c.chroma, c.hue), codeBg) >= NEED.step11;

    for (let iter = 0; iter < 600; iter++) {
      let worst = null;
      for (const kind of ['deuteranopia', 'protanopia']) {
        for (let i = 0; i < styleless.length; i++) {
          for (let j = i + 1; j < styleless.length; j++) {
            const d = deltaE(simulate(hexOf(styleless[i]), kind), simulate(hexOf(styleless[j]), kind));
            if (!worst || d < worst.d) worst = { d, a: styleless[i], b: styleless[j], kind };
          }
        }
      }
      if (!worst || worst.d >= NEED.cvdSyntax) break;
      const { a, b, kind } = worst;
      const lo = simLum(a, kind) <= simLum(b, kind) ? a : b;
      const hi = lo === a ? b : a;
      const STEP = 0.004;
      let moved = false;
      if (legible(lo, lo.L - STEP) && lo.L - STEP > 0.30) { lo.L -= STEP; moved = true; }
      if (hi.L + STEP < 0.985) { hi.L += STEP; moved = true; }
      if (!moved) break;   // nowhere left to go: --verify reports the shortfall honestly
    }
    codeTokens.forEach((c) => { c.hex = toHex(c.L, c.chroma, c.hue); });
  }

  const status = {
    warn: pinned({ ...STATUS.warn, bg: surfaceHexes[0], target: 4.5, mode }),
    dang: pinned({ ...STATUS.dang, bg: surfaceHexes[0], target: 4.5, mode }),
  };
  const warnScale = buildScale({ hue: STATUS.warn.hue, chroma: STATUS.warn.chroma, mode, beds: surfaceHexes });
  const dangScale = buildScale({ hue: STATUS.dang.hue, chroma: STATUS.dang.chroma, mode, beds: surfaceHexes });

  /* The focus ring must clear 3:1 against the page AND against the code island. One value
     cannot do both in light mode, so the island carries a scoped override — a local token,
     not a second rule to remember. */
  const h1 = hues[0].scale;
  const ringPage = h1.steps[8];
  const ringOnCode = pinned({ hue: hues[0].hue, chroma: 0.16, bg: codeBg, target: 3.0, mode: 'dark' });

  /* The pointer — see CURSOR_INK above. The halo is the DARK end of the neutral scale
     in whichever mode this is (step 12 in light, step 1 in dark), picked by luminance
     rather than by index so it cannot silently invert if the scale's direction ever
     changes. It has to be the dark end in BOTH modes because the ink is light in both. */
  const cursorHalo = [gray.steps[0], gray.steps[11]]
    .reduce((a, b) => (relLum(a) < relLum(b) ? a : b));
  const cursorInk = CURSOR_INK;

  return { gray, hues, textMid, washes, washBeds, surfaces, surfaceHexes, codeBg, codeBorder, codeText, codeMuted, codeTokens, status, warnScale, dangScale, ringPage, ringOnCode, cursorInk, cursorHalo };
}

/* ------------------------------------------------------------------ CSS emission */

function emitBlock(cfg, t, indent) {
  const p = ' '.repeat(indent);
  const L = [];
  const put = (k, v) => L.push(`${p}${k}: ${v};`);
  const gap = () => L.push('');

  L.push(`${p}/* neutral scale — hue ${cfg.grayHue}, chroma ${cfg.grayChroma} (tinted, not pure grey) */`);
  t.gray.steps.forEach((hex, i) => put(`--gray-${i + 1}`, hex));
  gap();
  t.hues.forEach((h, n) => {
    L.push(`${p}/* ${h.slot} — hue ${h.hue} */`);
    h.scale.steps.forEach((hex, i) => put(`--${h.slot}-${i + 1}`, hex));
    put(`--${h.slot}-on-solid`, h.scale.onSolid);
    gap();
  });

  const S = t.surfaces;
  L.push(`${p}/* ---- semantic layer: every role below names a step, never a value ---- */`);
  put('--bg', `var(--gray-${S.bg})`);
  put('--bg-subtle', `var(--gray-${S.bgSubtle})`);
  put('--surface', `var(--gray-${S.surface})`);
  put('--surface-raised', `var(--gray-${S.raised})`);
  put('--component', 'var(--gray-3)');
  put('--component-hover', 'var(--gray-4)');
  gap();
  L.push(`${p}/* The diagram's edge captions are drawn with a knockout stroke that has to MATCH`);
  L.push(`${p}   the card fill behind them. Naming that dependency stops it breaking silently`);
  L.push(`${p}   the day the card stops being --surface. */`);
  put('--knockout', `var(--gray-${S.surface})`);
  gap();
  L.push(`${p}/* borders: 6 is decorative and exempt from 1.4.11; 8 carries meaning at 3:1 */`);
  put('--border', 'var(--gray-6)');
  put('--border-strong', 'var(--gray-7)');
  put('--border-meaningful', 'var(--gray-8)');
  put('--graphic-line', 'var(--gray-8)');
  gap();
  L.push(`${p}/* text: three levels, ALL of which meet AA. The faintest is step 11 at 4.5:1 —`);
  L.push(`${p}   there is nothing below it, and reaching for one is what broke this before. */`);
  put('--text', 'var(--gray-12)');
  put('--text-muted', t.textMid);
  put('--text-faint', 'var(--gray-11)');
  gap();
  L.push(`${p}/* brand: 9 fills, 11 sets type. One token cannot do both jobs. */`);
  put('--primary', 'var(--hue1-9)');
  put('--primary-strong', 'var(--hue1-10)');
  put('--primary-text', 'var(--hue1-11)');
  put('--primary-text-strong', 'var(--hue1-12)');
  put('--primary-contrast', 'var(--hue1-on-solid)');
  put('--primary-subtle', 'var(--hue1-3)');
  put('--primary-line', 'var(--hue1-8)');
  gap();
  put('--accent', 'var(--hue2-9)');
  put('--accent-strong', 'var(--hue2-10)');
  put('--accent-text', 'var(--hue2-11)');
  put('--accent-text-strong', 'var(--hue2-12)');
  put('--accent-contrast', 'var(--hue2-on-solid)');
  put('--accent-subtle', 'var(--hue2-3)');
  put('--accent-line', 'var(--hue2-8)');
  gap();
  put('--tertiary', 'var(--hue3-9)');
  put('--tertiary-text', 'var(--hue3-11)');
  put('--tertiary-contrast', 'var(--hue3-on-solid)');
  put('--tertiary-subtle', 'var(--hue3-3)');
  put('--tertiary-line', 'var(--hue3-8)');
  gap();
  L.push(`${p}/* section washes — a surface tint per hue. Text is verified ON these too. */`);
  t.washes.forEach((w, i) => {
    put(`--wash-${i + 1}`, w.hexes[0]);
    put(`--wash-${i + 1}-deep`, w.hexes[1]);
  });
  gap();
  L.push(`${p}/* focus: must clear 3:1 against the page and against the dark code island */`);
  put('--focus-ring', t.ringPage);
  put('--focus-ring-on-code', t.ringOnCode);
  gap();
  L.push(`${p}/* the pointer: two-tone, constant across configurations. The ink is a stated`);
  L.push(`${p}   choice; the halo is the dark end of the neutral scale. On every surface at`);
  L.push(`${p}   least one of the two clears 4.5:1 — see CURSOR_INK in the generator. */`);
  put('--cursor-ink', t.cursorInk);
  put('--cursor-halo', t.cursorHalo);
  gap();
  L.push(`${p}/* status hues are constant across configurations — see STATUS in the generator */`);
  put('--warning', t.warnScale.steps[10]);
  put('--warning-solid', t.warnScale.steps[8]);
  put('--warning-subtle', t.warnScale.steps[2]);
  put('--danger', t.dangScale.steps[10]);
  put('--danger-solid', t.dangScale.steps[8]);
  put('--danger-subtle', t.dangScale.steps[2]);
  gap();
  L.push(`${p}/* code island: a dark surface in both themes, so tokens are pinned to it */`);
  put('--code-bg', t.codeBg);
  put('--code-border', t.codeBorder);
  put('--code-text', t.codeText);
  put('--code-muted', t.codeMuted);
  t.codeTokens.forEach((c) => put(`--code-${c.token}`, c.hex));

  return L.join('\n');
}

function emitCss(cfg) {
  const light = buildTheme(cfg, 'light');
  const dark = buildTheme(cfg, 'dark');
  return [
    START,
    `/* configuration: ${cfg.id} — "${cfg.name}"`,
    ` * ${cfg.character}`,
    ` * Regenerate with:  node scripts/generate-palette.mjs ${cfg.id}`,
    ` */`,
    ':root {',
    emitBlock(cfg, light, 2),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    emitBlock(cfg, dark, 4),
    '  }',
    '}',
    '',
    ':root[data-theme="dark"] {',
    emitBlock(cfg, dark, 2),
    '}',
    END,
  ].join('\n');
}

/* ------------------------------------------------------------------ verification */

function verify(cfg) {
  const rows = [];
  for (const mode of ['light', 'dark']) {
    const t = buildTheme(cfg, mode);
    const beds = t.surfaceHexes.concat(t.washBeds);
    const check = (label, fg, target, against) => {
      const worst = Math.min(...against.map((b) => contrast(fg, b)));
      const at = against[against.findIndex((b) => contrast(fg, b) === worst)];
      rows.push({ mode, label, fg, bed: at, ratio: +worst.toFixed(2), need: target, pass: worst >= target });
    };

    check('text (gray.12) on every surface', t.gray.steps[11], NEED.step12, beds);
    check('muted + caption (gray.11) on every surface', t.gray.steps[10], NEED.step11, beds);
    check('graphic line (gray.8) on every surface', t.gray.steps[7], NEED.step8, beds);
    t.hues.forEach((h) => {
      const own = [h.scale.steps[1], h.scale.steps[2]];
      check(`${h.slot} text (11) on surfaces + own tint`, h.scale.steps[10], NEED.step11, beds.concat(own));
      check(`${h.slot} solid (9) vs page`, h.scale.steps[8], NEED.step9, [beds[0]]);
      check(`${h.slot} text ON solid (9)`, h.scale.onSolid, NEED.onSolid, [h.scale.steps[8]]);
      check(`${h.slot} line (8) on every surface`, h.scale.steps[7], NEED.step8, beds.concat(own));
    });
    check('muted mid level (7:1 AAA) on every surface', t.textMid, 7.0, beds);
    check('warning text on surfaces', t.warnScale.steps[10], NEED.step11, beds);
    check('danger text on surfaces', t.dangScale.steps[10], NEED.step11, beds);
    check('code text on code bg', t.codeText, 13, [t.codeBg]);
    check('code muted on code bg', t.codeMuted, NEED.step11, [t.codeBg]);
    t.codeTokens.forEach((c) => check(`code ${c.token} on code bg`, c.hex, NEED.step11, [t.codeBg]));
    check('focus ring vs page', t.ringPage, 3.0, [beds[0]]);
    check('focus ring vs code island', t.ringOnCode, 3.0, [t.codeBg]);
    /* The pointer is a PAIR, so the obligation is on the pair: every surface it can
       cross must be cleared by at least one of the two tones. Checking the ink alone
       is the wrong test for a two-tone mark — it would reject a pale ink that a dark
       rim makes perfectly visible, and it would pass a mid-tone ink whose rim adds
       nothing on the code island. */
    const cursorBeds = beds.concat([t.codeBg]);
    const pairWorst = Math.min(...cursorBeds.map((b) =>
      Math.max(contrast(t.cursorInk, b), contrast(t.cursorHalo, b))));
    const pairBed = cursorBeds.find((b) =>
      Math.max(contrast(t.cursorInk, b), contrast(t.cursorHalo, b)) === pairWorst);
    rows.push({
      mode, label: 'cursor pair (ink OR halo) on every surface it crosses',
      fg: `${t.cursorInk}/${t.cursorHalo}`, bed: pairBed,
      ratio: +pairWorst.toFixed(2), need: 4.5, pass: pairWorst >= 4.5,
    });
    check('cursor ink vs its own halo', t.cursorInk, 3.0, [t.cursorHalo]);

    /* Mutual distinguishability of the syntax set — measured through BOTH dichromat
       simulations, because a syntax highlighter is the one thing on this page that cannot
       add a label or an icon: colour is genuinely its only channel. Normal-vision
       separation is not reported, since it is never the binding constraint. */
    const worstPair = { d: Infinity };
    for (const kind of ['deuteranopia', 'protanopia']) {
      const colourOnly = t.codeTokens.filter((c) => !c.styled);
      for (let i = 0; i < colourOnly.length; i++) {
        for (let j = i + 1; j < colourOnly.length; j++) {
          const a = colourOnly[i], b = colourOnly[j];
          const d = deltaE(simulate(a.hex, kind), simulate(b.hex, kind));
          if (d < worstPair.d) Object.assign(worstPair, { d, kind, a: a.token, b: b.token, ah: a.hex, bh: b.hex });
          rows.push({ mode, cvd: true, label: `syntax ${a.token}/${b.token} under ${kind}`,
            fg: a.hex, bed: b.hex, ratio: +d.toFixed(3), need: NEED.cvdSyntax, pass: d >= NEED.cvdSyntax });
        }
      }
      /* And the brand hues, at the two steps where they carry meaning. */
      for (const st of [9, 11]) {
        for (let i = 0; i < t.hues.length; i++) {
          for (let j = i + 1; j < t.hues.length; j++) {
            const a = t.hues[i], b = t.hues[j];
            const d = deltaE(simulate(a.scale.steps[st - 1], kind), simulate(b.scale.steps[st - 1], kind));
            rows.push({ mode, cvd: true, label: `${a.slot}/${b.slot} step ${st} under ${kind}`,
              fg: a.scale.steps[st - 1], bed: b.scale.steps[st - 1], ratio: +d.toFixed(3), need: NEED.cvdBrand, pass: d >= NEED.cvdBrand });
          }
        }
      }
    }
    rows.push({ mode, label: `WORST syntax pair (${worstPair.kind}: ${worstPair.a}/${worstPair.b})`,
      fg: worstPair.ah, bed: worstPair.bh, ratio: +worstPair.d.toFixed(3), need: NEED.cvdSyntax, pass: worstPair.d >= NEED.cvdSyntax });

    t.codeTokens.filter((c) => c.chroma < 0.05).forEach((c) => {
      const gap = contrast(t.codeText, t.codeBg) / contrast(c.hex, t.codeBg);
      rows.push({ mode, label: `syntax ${c.token} recedes from plain code text`, fg: c.hex, bed: t.codeText, ratio: +gap.toFixed(2), need: 1.35, pass: gap >= 1.35 });
    });
  }
  return rows;
}

/* OKLab hue angle difference, for "are these two token colours telling me apart?" */
function rgbToOklab(hex) {
  const [r, g, b] = hexToRgb(hex).map((v) => srgbToLinear(v / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return {
    L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    a: 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    b: 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  };
}
/* OKLab Euclidean distance — a perceptual "can I tell these apart" number. Used on
   SIMULATED colours, which is the only way to answer the question for a dichromat. */
function deltaE(h1, h2) {
  const A = rgbToOklab(h1), B = rgbToOklab(h2);
  return Math.hypot(A.L - B.L, A.a - B.a, A.b - B.b);
}

function deltaHue(h1, h2) {
  const A = rgbToOklab(h1), B = rgbToOklab(h2);
  const a1 = (Math.atan2(A.b, A.a) * 180) / Math.PI, a2 = (Math.atan2(B.b, B.a) * 180) / Math.PI;
  let d = Math.abs(a1 - a2) % 360;
  return d > 180 ? 360 - d : d;
}

